"""
VeloC Automated C/C++ Header Binding Generator (veloc bindgen)
Parses C/C++ header files, extracts struct layouts, enums, and function prototypes,
and emits safe, idiomatic VeloC declarations with RAII wrappers and Result return types.
"""

import re
import sys
from pathlib import Path
from typing import List, Dict, Any, Tuple, Optional

ROOT = Path("D:/VeloC")

TYPE_MAP = {
    "void": "void",
    "char": "u8",
    "const char*": "*const u8",
    "char*": "*mut u8",
    "int": "i32",
    "unsigned int": "u32",
    "uint32_t": "u32",
    "int32_t": "i32",
    "int64_t": "i64",
    "uint64_t": "u64",
    "size_t": "usize",
    "float": "f32",
    "double": "f64",
    "bool": "bool"
}

class VeloCBindgen:
    def __init__(self):
        self.structs = []
        self.functions = []

    def parse_header(self, header_content: str):
        # 1. Strip comments
        clean = re.sub(r"/\*.*?\*/", "", header_content, flags=re.DOTALL)
        clean = re.sub(r"//.*", "", clean)

        # 2. Extract structs
        struct_matches = re.finditer(r"struct\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\{([^}]*)\};", clean)
        for m in struct_matches:
            name = m.group(1)
            body = m.group(2)
            fields = []
            for line in body.split(";"):
                parts = line.strip().split()
                if len(parts) >= 2:
                    ctype = " ".join(parts[:-1])
                    fname = parts[-1].strip("*")
                    if "*" in parts[-1]:
                        ctype += "*"
                    vtype = TYPE_MAP.get(ctype, ctype)
                    fields.append((fname, vtype))
            self.structs.append((name, fields))

        # 3. Extract functions
        fn_matches = re.finditer(r"([a-zA-Z0-9_*]+(?:\s+[a-zA-Z0-9_*]+)?)\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\(([^)]*)\)\s*;", clean)
        for m in fn_matches:
            ret_type = m.group(1).strip()
            name = m.group(2)
            params_raw = m.group(3).strip()
            
            if name in ("struct", "return", "if", "for", "while"):
                continue

            params = []
            if params_raw and params_raw != "void":
                for p in params_raw.split(","):
                    p_parts = p.strip().split()
                    if len(p_parts) >= 2:
                        p_type = " ".join(p_parts[:-1])
                        p_name = p_parts[-1].strip("*")
                        if "*" in p_parts[-1]:
                            p_type += "*"
                        params.append((p_name, TYPE_MAP.get(p_type, p_type)))

            self.functions.append((name, TYPE_MAP.get(ret_type, ret_type), params))

    def generate_veloc(self) -> str:
        out = [
            "// Auto-generated by VeloC Bindgen v1.0.0",
            "// Do not edit manually.",
            ""
        ]

        # Emitting Structs
        for sname, fields in self.structs:
            out.append("#[repr(C)]")
            out.append(f"pub struct {sname} {{")
            for fname, ftype in fields:
                out.append(f"    {fname}: {ftype},")
            out.append("}\n")

        # Emitting Extern C Block
        out.append('extern "C" {')
        for fname, ret, params in self.functions:
            plist = ", ".join(f"{pname}: {ptype}" for pname, ptype in params)
            out.append(f"    fn {fname}({plist}) -> {ret};")
        out.append("}\n")

        # Emitting Safe RAII Wrappers for Functions returning error codes
        out.append("// Safe Idiomatic VeloC Wrappers")
        for fname, ret, params in self.functions:
            plist = ", ".join(f"{pname}: {ptype}" for pname, ptype in params)
            arg_names = ", ".join(pname for pname, _ in params)
            if ret == "i32" and ("init" in fname or "open" in fname or "create" in fname):
                out.append(f"pub fn safe_{fname}({plist}) -> Result<bool, &'static str> {{")
                out.append(f"    let code = unsafe {{ {fname}({arg_names}) }};")
                out.append("    if code == 0 {")
                out.append("        return Result::Ok(true);")
                out.append("    } else {")
                out.append('        return Result::Err("Operation failed with error code");')
                out.append("    }")
                out.append("}\n")

        return "\n".join(out)

def generate_bindings(header_path: Path, output_path: Optional[Path] = None) -> Path:
    if output_path is None:
        output_path = header_path.with_suffix(".vc")

    bg = VeloCBindgen()
    bg.parse_header(header_path.read_text(encoding="utf-8"))
    content = bg.generate_veloc()
    output_path.write_text(content, encoding="utf-8")
    return output_path

